export function getTemperatureStatus(temp: number): {
  status: "deep-freeze" | "safe" | "warning" | "high";
  label: string;
  color: string;
  badgeBg: string;
  badgeText: string;
} {
  if (temp < 0) {
    return {
      status: "deep-freeze",
      label: "Deep Freeze",
      color: "#00B4D8",
      badgeBg: "bg-cyan-500/10 text-cyan-600 dark:text-cyan-400 border-cyan-500/20",
      badgeText: "text-cyan-500",
    };
  }
  if (temp <= 40) {
    return {
      status: "safe",
      label: "In-Range",
      color: "#10B981",
      badgeBg: "bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border-emerald-500/20",
      badgeText: "text-emerald-500",
    };
  }
  if (temp <= 50) {
    return {
      status: "warning",
      label: "Warning",
      color: "#F59E0B",
      badgeBg: "bg-amber-500/10 text-amber-600 dark:text-amber-400 border-amber-500/20",
      badgeText: "text-amber-500",
    };
  }
  return {
    status: "high",
    label: "High Critical",
    color: "#EF4444",
    badgeBg: "bg-rose-500/10 text-rose-600 dark:text-rose-400 border-rose-500/20",
    badgeText: "text-rose-500",
  };
}

// Generate realistic 24-hr history curve around a base temperature and humidity
function generateHistory(baseTemp: number, baseHumidity: number) {
  const times = [
    "00:00", "02:00", "04:00", "06:00", "08:00", "10:00",
    "12:00", "14:00", "16:00", "17:30", "18:00", "20:00", "22:00"
  ];
  return times.map((time, idx) => {
    const tempNoise = Math.sin(idx * 0.7) * 2.5 + (Math.random() - 0.5) * 1.2;
    const humNoise = Math.cos(idx * 0.6) * 4 + (Math.random() - 0.5) * 2;
    return {
      time,
      temperature: Math.round((baseTemp + tempNoise) * 10) / 10,
      humidity: Math.max(0, Math.min(100, Math.round(baseHumidity + humNoise))),
    };
  });
}

